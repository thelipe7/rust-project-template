def snapshot_without_git(destination: Path) -> Path:
    """Copies the template to `destination`, leaving `.git` behind.

    Copier reads a local template that is a Git repository at its latest tag,
    not as it sits on disk — correct for someone generating a project, and
    wrong for a test suite, which would then be checking the last release
    instead of the change being made. Without a `.git` directory there is no
    tag to prefer and Copier reads the files.

    `symlinks=True` because `AGENTS.md` is one, and the suite checks that it
    still is on the other side.
    """
    shutil.copytree(
        TEMPLATE_ROOT,
        destination,
        dirs_exist_ok=True,
        ignore=shutil.ignore_patterns(".git", "__pycache__"),
        symlinks=True,
    )
    return destination


class TemplateGenerationTests(unittest.TestCase):
    template: Path

    @classmethod
    def setUpClass(cls) -> None:
        cls._snapshot = tempfile.TemporaryDirectory()
        cls.addClassCleanup(cls._snapshot.cleanup)
        cls.template = snapshot_without_git(Path(cls._snapshot.name))

    def render(self, *, project_kind: str, **overrides: str) -> Path:
        temporary = tempfile.TemporaryDirectory()
        self._temporary_directories.append(temporary)
        self.addCleanup(temporary.cleanup)
        destination = Path(temporary.name)
        answers = ANSWERS | {"project_kind": project_kind} | overrides
        arguments = []
        for question, answer in answers.items():
            arguments += ["--data", f"{question}={answer}"]
        subprocess.run(
            [
                "copier",
                "copy",
                "--trust",
                "--defaults",
                *arguments,
                str(self.template),
                str(destination),
            ],
            check=True,
        )
        return destination

    def setUp(self) -> None:
        self._temporary_directories: list[tempfile.TemporaryDirectory[str]] = []

    def paths_in(self, generated: Path) -> set[str]:
        return {
            path.relative_to(generated).as_posix()
            for path in generated.rglob("*")
        }

