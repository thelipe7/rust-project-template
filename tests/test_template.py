    def test_a_generated_project_passes_its_own_gate(self) -> None:
        """`cargo xtask ci` is what a generated project asks of every change,
        including the first one. A template that hands a project a gate it
        cannot pass has handed it a problem to fix before it can start.

        This is where rendering shows: `cargo fmt --check` fails on a blank
        line a Jinja block left behind, and `cargo deny` fails on a member
        crate whose manifest names no license.
        """
        for project_kind in ("published_library", "workspace_app"):
            with self.subTest(project_kind=project_kind):
                generated = self.render(project_kind=project_kind)
                subprocess.run(
                    ["cargo", "xtask", "ci"],
                    cwd=generated,
                    check=True,
                )

                # And the feature and lint tasks again with a dev-dependency in
                # the tree: `cargo hack --no-dev-deps` hands cargo a manifest
                # without that table, and the flags beside it must tolerate the
                # re-resolve. The skeleton has no dev-dependencies, which is
                # exactly how an incompatible `--locked` once shipped
                # unnoticed. itoa, because it has none of its own.
                subprocess.run(
                    ["cargo", "add", "--dev", "itoa@1", "--package", "example-ui"],
                    cwd=generated,
                    check=True,
                )
                # Anchored where a dev-dependency is actually visible: an
                # integration test for the library, a `#[cfg(test)]` module
                # for the binary — `use` in plain binary code cannot see it.
                if project_kind == "published_library":
                    anchor, snippet = (
                        "tests/public_api.rs",
                        "\n// Anchors the dev-dependency for cargo-machete.\n"
                        "use itoa as _;\n",
                    )
                else:
                    anchor, snippet = (
                        "apps/example-ui/src/main.rs",
                        "\n// Anchors the dev-dependency for cargo-machete.\n"
                        "#[cfg(test)]\n"
                        "mod dev_dependency_anchor {\n"
                        "    use itoa as _;\n"
                        "}\n",
                    )
                with open(generated / anchor, "a", encoding="utf-8") as file:
                    file.write(snippet)
                for task in ("lint", "features"):
                    subprocess.run(
                        ["cargo", "xtask", task],
                        cwd=generated,
                        check=True,
                    )

    def test_the_fuzz_task_finds_every_fuzz_crate_and_stays_out_of_the_gate(
        self,
    ) -> None:
        """A fuzz crate is a workspace of its own — nightly and a sanitizer,
        deliberately outside the tree the gate compiles — so nothing else
        builds its targets, and a change to the API a target calls breaks it
        silently and stays broken. `cargo xtask fuzz` is what compiles them,
        and it finds them rather than being told where they are: `fuzz/` at
        the root, which the scaffold writes, and `crates/<name>/fuzz`, which a
        workspace grows by hand.

        Building a real target needs nightly and cargo-fuzz, which this suite
        does not require, so what is asserted here is the discovery: nothing
        found is a success, and a directory found is an attempt to build it —
        an attempt that fails, because these stubs are not crates.

        Compiling a target is a check; running one is a search. The search
        stays out of the gate and out of CI, which is the other half of this.
        """
        generated = self.render(project_kind="workspace_app")

        # The case most projects are in, and so the one that must not be
        # something to remember to ignore.
        subprocess.run(["cargo", "xtask", "fuzz"], cwd=generated, check=True)

        for planted, layout in (("fuzz", "fuzz"), ("crates/parser", "crates/parser/fuzz")):
            with self.subTest(layout=layout):
                stub = generated / layout / "Cargo.toml"
                stub.parent.mkdir(parents=True)
                stub.write_text("# Not a crate.\n", encoding="utf-8")
                # A crate under `crates/` is a workspace member, and one
                # without a manifest fails the workspace rather than the task
                # — which would pass this test for the wrong reason.
                if layout.startswith("crates/"):
                    (stub.parent.parent / "src").mkdir()
                    (stub.parent.parent / "src/lib.rs").write_text(
                        "", encoding="utf-8"
                    )
                    (stub.parent.parent / "Cargo.toml").write_text(
                        '[package]\nname = "parser"\n'
                        'version = "0.0.0"\nedition = "2024"\n'
                        'license = "MIT"\n',
                        encoding="utf-8",
                    )
                found = subprocess.run(
                    ["cargo", "xtask", "fuzz"],
                    cwd=generated,
                    capture_output=True,
                )
                shutil.rmtree(generated / planted)
                # The task's own words for a child that ran and failed, which
                # is what proves it stood in that directory and started one.
                self.assertIn(
                    "`cargo` exited with",
                    found.stderr.decode(),
                    f"`cargo xtask fuzz` did not look inside {layout}",
                )

        # Named where somebody looks for it, and nowhere it would run.
        usage = subprocess.run(["cargo", "xtask"], cwd=generated, capture_output=True)
        self.assertIn("fuzz", usage.stderr.decode())
        source = (generated / "xtask/src/main.rs").read_text(encoding="utf-8")
        self.assertNotIn('run("fuzz")', source)
        self.assertIn(
            "cargo xtask fuzz",
            (generated / "CONTRIBUTING.md").read_text(encoding="utf-8"),
        )
        for workflow in (generated / ".github/workflows").iterdir():
            self.assertNotIn(
                "xtask fuzz", workflow.read_text(encoding="utf-8"), str(workflow)
            )

    def test_all_supported_profile_combinations_render(self) -> None:
        for project_kind in ("published_library", "workspace_app"):
            for unsafe_policy in ("deny", "scoped"):
                for clippy_pedantic in ("true", "false"):
                    with self.subTest(
                        project_kind=project_kind,
                        unsafe_policy=unsafe_policy,
                        clippy_pedantic=clippy_pedantic,
                    ):
                        self.assert_profile_combination_renders(
                            project_kind, unsafe_policy, clippy_pedantic
                        )

    def assert_profile_combination_renders(
        self, project_kind: str, unsafe_policy: str, clippy_pedantic: str
    ) -> None:
        generated = self.render(
            project_kind=project_kind,
            unsafe_policy=unsafe_policy,
            clippy_pedantic=clippy_pedantic,
        )
        manifest = (generated / "Cargo.toml").read_text(encoding="utf-8")
        expected = "deny" if unsafe_policy == "deny" else "warn"
        self.assertIn(f'unsafe_code = "{expected}"', manifest)
        # Enabled whole or absent whole — the question the template asks is
        # about the group, never about individual pedantic lints.
        self.assertEqual(
            'pedantic = { level = "warn", priority = -1 }' in manifest,
            clippy_pedantic == "true",
        )
        # Miri answers a question only code allowed to write
        # `unsafe` can raise, and it costs an order of magnitude
        # in CI minutes to ask.
        self.assertEqual(
            (generated / ".github/workflows/miri.yml").exists(),
            unsafe_policy == "scoped",
        )
        # A library promises a minimum toolchain to whoever
        # depends on it; an application ships binaries and
        # promises nothing to a compiler. Each carries the release
        # path and checks that fit it, and neither the other's.
        library = project_kind == "published_library"
        paths = self.paths_in(generated)
        for path, belongs_to_a_library in (
            (".github/workflows/release.yml", True),
            (".github/workflows/msrv.yml", True),
            (".github/workflows/minimal-versions.yml", True),
            (".github/workflows/package.yml", True),
            ("fixtures/consumer/Cargo.toml", True),
            ("tests/public_api.rs", True),
            ("crates/README.md", False),
            # An application is the kind whose release workflow is generated
            # rather than written, and this is what tells actionlint not to
            # report dist's shell style as though somebody could fix it.
            (".github/actionlint.yaml", False),
            (".github/zizmor.yml", False),
            (".github/workflows/release-gate.yml", False),
            (".github/workflows/sbom.yml", False),
            (".github/workflows/dist-check.yml", False),
            ("dist-workspace.toml", False),
        ):
            self.assertEqual(
                path in paths,
                library == belongs_to_a_library,
                f"{path} in a {project_kind}",
            )

