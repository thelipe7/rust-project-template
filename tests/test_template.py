from __future__ import annotations

import re
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path


TEMPLATE_ROOT = Path(__file__).resolve().parents[1]

# `uses:` as a YAML key, anchored to the start of its line. Unanchored, this
# also matches the pin check's own grep pattern, which is a shell string
# inside a `run:` block that happens to contain the word.
USES = re.compile(r"^\s*-?\s*uses:\s*(\S+)", re.MULTILINE)

# Every question the template asks, answered. The template carries no defaults
# — a default is an answer nobody gave — so a generation that omits one fails,
# and this suite answers every question like any other caller.
ANSWERS = {
    "project_name": "example-ui",
    "project_description": "An example package generated by the project template.",
    "github_owner": "example-owner",
    "keywords": "example, template",
    "categories": "development-tools",
    "rust_toolchain": "1.97.1",
    "rust_version": "1.92",
    "license_expression": "MIT",
    "copyright_holder": "Example Holder",
    "copyright_year": "2026",
    "unsafe_policy": "deny",
    "clippy_pedantic": "true",
    # The opt-in verification surfaces, all on: the suite's job is to check
    # what the template can generate, and `yes` is the answer that generates
    # something to check. The opt-out is what the dedicated test renders.
    "openssf_scorecard": "true",
    "mutation_testing": "true",
    "fuzzing": "true",
}


def snapshot_without_git(destination: Path) -> Path:
    """Copies the template to `destination`, leaving `.git` behind.

    Copier reads a local template that is a Git repository at its latest tag,
    not as it sits on disk — correct for someone generating a project, and
    wrong for a test suite, which would then be checking the last release
    instead of the change being made. Without a `.git` directory there is no
    tag to prefer and Copier reads the files.

    `symlinks=True` because `AGENTS.md` is one, and the suite checks that it
    still is on the other side.
    """
    shutil.copytree(
        TEMPLATE_ROOT,
        destination,
        dirs_exist_ok=True,
        ignore=shutil.ignore_patterns(".git", "__pycache__"),
        symlinks=True,
    )
    return destination


class TemplateGenerationTests(unittest.TestCase):
    template: Path

    @classmethod
    def setUpClass(cls) -> None:
        cls._snapshot = tempfile.TemporaryDirectory()
        cls.addClassCleanup(cls._snapshot.cleanup)
        cls.template = snapshot_without_git(Path(cls._snapshot.name))

    def render(self, *, project_kind: str, **overrides: str) -> Path:
        temporary = tempfile.TemporaryDirectory()
        self._temporary_directories.append(temporary)
        self.addCleanup(temporary.cleanup)
        destination = Path(temporary.name)
        answers = ANSWERS | {"project_kind": project_kind} | overrides
        arguments = []
        for question, answer in answers.items():
            arguments += ["--data", f"{question}={answer}"]
        subprocess.run(
            [
                "copier",
                "copy",
                "--trust",
                "--defaults",
                *arguments,
                str(self.template),
                str(destination),
            ],
            check=True,
        )
        return destination

    def setUp(self) -> None:
        self._temporary_directories: list[tempfile.TemporaryDirectory[str]] = []

    def paths_in(self, generated: Path) -> set[str]:
        return {
            path.relative_to(generated).as_posix()
            for path in generated.rglob("*")
        }

